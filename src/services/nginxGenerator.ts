/**
 * Validates Nginx configuration syntax
 */
export function validateNginxSyntax(config: string): {
  valid: boolean;
  errors: string[];
  warnings: string[];
} {
  const errors: string[] = [];
  const warnings: string[] = [];

  const lines = config.split('\n');
  let braceCount = 0;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const lineNum = i + 1;
    const trimmed = rawLine.trim();

    // Skip empty lines and full comment lines
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    // Check brace balance
    for (const char of trimmed) {
      if (char === '{') braceCount++;
      if (char === '}') braceCount--;
    }

    if (braceCount < 0) {
      errors.push(`Line ${lineNum}: Unexpected closing brace '}'`);
    }

    // Check semicolon requirement for directives
    if (
      !trimmed.endsWith('{') &&
      !trimmed.endsWith('}') &&
      !trimmed.endsWith(';') &&
      !trimmed.startsWith('#')
    ) {
      // Directives must terminate with a semicolon
      errors.push(`Line ${lineNum}: Directive "${trimmed.slice(0, 30)}..." is missing trailing semicolon ';'`);
    }

    // Check invalid tokens
    if (trimmed.includes('undefined') || trimmed.includes('NaN')) {
      errors.push(`Line ${lineNum}: Invalid configuration value containing undefined or NaN`);
    }
  }

  if (braceCount !== 0) {
    errors.push(`Unbalanced braces in configuration: ${Math.abs(braceCount)} ${braceCount > 0 ? 'unclosed' : 'extra closed'} block(s)`);
  }

  return {
    valid: errors.length === 0,
    errors,
    warnings,
  };
}
