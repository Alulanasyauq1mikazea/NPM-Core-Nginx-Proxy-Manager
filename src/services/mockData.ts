function generateInitialHistory(baseRps: number, baseLatency: number) {
  const points = [];
  const now = Date.now();
  for (let i = 20; i >= 0; i--) {
    const variance = (Math.random() - 0.48) * 0.3;
    const rps = Math.max(5, Math.round(baseRps * (1 + variance)));
    const latency = Math.max(3, parseFloat((baseLatency * (1 + variance * 0.8)).toFixed(1)));
    points.push({
      timestamp: now - i * 3000,
      rps,
      latencyMs: latency,
      bandwidthKbps: Math.round(rps * 4.2),
      status2xx: Math.round(rps * 0.95),
      status4xx: Math.round(rps * 0.04),
      status5xx: Math.round(rps * 0.01),
    });
  }
  return points;
}

